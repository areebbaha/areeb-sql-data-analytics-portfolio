-- Q35 -  Find the top 3 customers who:
/*
have placed more than 2 orders
have purchased products from more than one category
have total spending greater than ₹30,000
consider only Delivered orders
display customer name, order count, total spending
sort by total spending descending
*/
select c.customer_name,COUNT(DISTINCT ca.category_id) AS number_of_categories,count(distinct o.order_id) as order_count,sum(oi.quantity*oi.unit_price) as total_spending 
from customers c 
inner join orders o on c.customer_id=o.customer_id inner join order_items oi on oi.order_id=o.order_id inner join products p on oi.product_id=p.product_id
inner join categories ca on ca.category_id=p.category_id
where o.order_status='delivered' group by c.customer_name,c.customer_id
having order_count>2 and total_spending>30000 and number_of_categories>1
order by total_spending desc limit 3;

































































































