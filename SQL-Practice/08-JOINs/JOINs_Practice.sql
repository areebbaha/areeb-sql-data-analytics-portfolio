on oi.order_id=o.order_id inner join customers c on c.customer_id=o.customer_id group by c.customer_name,c.customer_id;

-- Q22 - Display customers whose average order value is greater than ₹15,000.
select c.customer_name,c.customer_id,sum(oi.quantity*oi.unit_price) /count(distinct o.order_id) as avg_order_value from order_items oi 
inner join orders o on oi.order_id=o.order_id
inner join customers c on c.customer_id=o.customer_id group by c.customer_name,c.customer_id having avg_order_value >15000 ;

-- Q23 - Find the number of orders for each order status.
