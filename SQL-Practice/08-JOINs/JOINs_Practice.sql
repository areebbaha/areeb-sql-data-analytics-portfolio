 inner join order_items oi on o.order_id=oi.order_id group by c.customer_name,c.customer_id order by total_spending desc limit 5;
 
-- Q16 - Find customers whose total spending is greater than ₹30,000.
select c.customer_name,c.customer_id,sum(oi.quantity*oi.unit_price) as total_spending from customers c inner join orders o on c.customer_id=o.customer_id 
inner join order_items oi on o.order_id=oi.order_id group by c.customer_name,c.customer_id having total_spending>30000;

-- Q17 - Find the total revenue generated by each product category.
select c.category_name,p.category_id,sum(oi.quantity*oi.unit_price) as total_revenue from order_items oi 
inner join products p on oi.product_id=p.product_id inner join categories c on c.category_id=p.category_id group by c.category_name,p.category_id;

-- Q18 - Display categories whose total revenue is greater than ₹50,000, sorted by revenue from highest to lowest.
select c.category_name,p.category_id,sum(oi.quantity*oi.unit_price) as total_revenue from order_items oi 
inner join products p on oi.product_id=p.product_id inner join categories c on c.category_id=p.category_id group by c.category_name,p.category_id 
having total_revenue>50000 order by total_revenue desc ;

-- Q19 - Find the number of orders handled by each employee.
select count(order_id) as number_of_orders,e.employee_id,e.employee_name from orders o inner join employees e on o.employee_id=e.employee_id
 group by e.employee_name,e.employee_id;
 
-- Q20 - Display employees who have handled more than 3 orders.
select count(order_id) as number_of_orders,e.employee_id,e.employee_name from orders o inner join employees e on o.employee_id=e.employee_id
 group by e.employee_name,e.employee_id having number_of_orders>3;
 
-- Q21 - Find the average order value for each customer.
