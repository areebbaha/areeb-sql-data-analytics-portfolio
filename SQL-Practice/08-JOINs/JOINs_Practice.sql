-- Q10 - Display the product name, category name, brand, and price for every product.
select c.category_name,c.category_id,p.product_name,p.price,p.brand from products p inner join categories c on p.category_id=c.category_id;

-- Q11 - Find the total quantity sold for each product.
select p.product_name,sum(oi.quantity) as total_quantity from order_items oi inner join products p on p.product_id=oi.product_id group by product_name;

-- Q12 - Find the total revenue generated by each product using: quantity × unit_price
select p.product_name,sum(oi.quantity*oi.unit_price) as total_revenue from order_items oi inner join
 products p on oi.product_id=p.product_id group by p.product_name;
 
-- Q13 - Display the top 5 products by total revenue.
select p.product_name,sum(oi.quantity*oi.unit_price) as total_revenue from order_items oi inner join
 products p on oi.product_id=p.product_id group by p.product_name order by total_revenue desc limit 5;
 
-- Q14 - Find the total amount spent by each customer.
