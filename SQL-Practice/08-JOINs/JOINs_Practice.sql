-- Q25 - Categorize products based on price: Below ₹5,000 → Budget ₹5,000–₹15,000 → Standard Above ₹15,000 → Premium
select product_name,case when p.price <5000 then 'budget' 
when p.price between 5000 and 15000 then 'standard'
else 'premium'
end as categorised_products from products p;

-- Q27 - Count how many products belong to each price category.
select count(*),case when p.price <5000 then 'budget' 
when p.price between 5000 and 15000 then 'standard'
else 'premium'
end as price_category from products p group by case when p.price <5000 then 'budget' 
when p.price between 5000 and 15000 then 'standard'
else 'premium'
end;

