-- Q1 - Display the names and cities of all customers from Hyderabad.
select customer_name,city from customers where city='hyderabad';

-- Q2 - Display each order along with the customer name, order date, and order status.
select o.order_id,c.customer_id,c.customer_name,o.order_status,o.order_date from orders o inner join customers c on o.customer_id=c.customer_id;

-- Q3 - Find all customers who have placed at least one order.
select distinct c.customer_name, c.customer_id  from customers c inner join orders o on c.customer_id=o.customer_id; 

-- Q4 - Display the customer name, order ID, and payment method for orders paid using UPI or Credit Card.
select c.customer_name, c.customer_id ,o.order_id,o.payment_method from customers c inner join orders o on c.customer_id=o.customer_id 
where o.payment_method in ('UPI','CREDIT CARD'); 

-- Q5 - Display all products whose price is between ₹5,000 and ₹20,000, sorted from highest to lowest price.
select * from products where price between 5000 and 20000 order by price desc; 

-- Q6 - Find the number of orders placed by each customer.
SELECT c.customer_id,c.customer_name,COUNT(o.order_id) AS number_of_orders
FROM customers c INNER JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name;

-- Q7 - Display all customers, including customers who have never placed an order.
select c.customer_name, c.customer_id ,o.order_id from customers c left join orders o on c.customer_id=o.customer_id;
 
-- Q8 - Find the customers who have never placed an order.
select c.customer_name, c.customer_id ,o.order_id from customers c left join orders o on c.customer_id=o.customer_id where o.order_id is null; 

